package com.App.SRP;

public class Student {

	String name;
	long id=0;
	int classGrade=1;
	String grade;
	double total=0;
	double average=0;
	double math=0;
	double science=0;
	double english=0;
	double computerScience=0;
	double spanish=0;
	String schoolName;
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public long getId() {
		return id;
	}
	public void setId(long id) {
		this.id = id;
	}
	public int getClassGrade() {
		return classGrade;
	}
	public void setClassGrade(int classGrade) {
		this.classGrade = classGrade;
	}
	public String getGrade() {
		return grade;
	}
	public void setGrade(String grade) {
		this.grade = grade;
	}
	public double getTotal() {
		return total;
	}
	public void setTotal(double total) {
		this.total = total;
	}
	public double getAverage() {
		return average;
	}
	public void setAverage(double average) {
		this.average = average;
	}
	public double getMath() {
		return math;
	}
	public void setMath(double math) {
		this.math = math;
	}
	public double getScience() {
		return science;
	}
	public void setScience(double science) {
		this.science = science;
	}
	public double getEnglish() {
		return english;
	}
	public void setEnglish(double english) {
		this.english = english;
	}
	public double getComputerScience() {
		return computerScience;
	}
	public void setComputerScience(double computerScience) {
		this.computerScience = computerScience;
	}
	public double getSpanish() {
		return spanish;
	}
	public void setSpanish(double spanish) {
		this.spanish = spanish;
	}
	public String getSchoolName() {
		return schoolName;
	}
	public void setSchoolName(String schoolName) {
		this.schoolName = schoolName;
	}
	
	
	
}
